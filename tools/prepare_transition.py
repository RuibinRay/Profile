#!/usr/bin/env python3
"""
prepare_transition.py — turn a short video of one painting becoming the next into frames the film scrubs.

    python3 tools/prepare_transition.py clip.mp4 --for night-house            # add or replace a clip
    python3 tools/prepare_transition.py --remove night-house                   # go back to the shader
    python3 tools/prepare_transition.py --list

`--for` is "<from>-<to>" with the shot ids of assets/js/cinema/storyboard.js (the names of the pairs
written by tools/transition_frames.py without their number: night-house, house-blossom, …).

The video is sampled into 48 evenly spaced frames (--frames) at 1280 × 720 and written, as AVIF and
WebP, to assets/transitions/<from>-<to>/; assets/js/cinema/clips.js lists what exists. The film loads
only the frames around the scroll position, so a visitor who never reaches the transition downloads none.

Needs ffmpeg and Pillow.
"""
import argparse, json, os, re, shutil, subprocess, sys, tempfile
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'assets', 'transitions')
LIST = os.path.join(ROOT, 'assets', 'js', 'cinema', 'clips.js')
HEAD = ('// Generated by tools/prepare_transition.py — do not edit by hand.\n'
        '// A transition listed here ("<from>-<to>", the shot ids of storyboard.js) is played from pre-rendered\n'
        '// frames, scrubbed by the scroll, instead of being drawn by the shader. With no entry, the shader draws it.\n')


def read():
    m = re.search(r'export const CLIPS = (\{.*\});', open(LIST).read(), re.S) if os.path.exists(LIST) else None
    return json.loads(m.group(1)) if m else {}


def write(clips):
    with open(LIST, 'w') as f:
        f.write(HEAD + 'export const CLIPS = ' + json.dumps(clips, indent=1) + ';\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('video', nargs='?')
    ap.add_argument('--for', dest='name', help='"<from>-<to>" shot ids, for example night-house')
    ap.add_argument('--frames', type=int, default=48)
    ap.add_argument('--width', type=int, default=1280)
    ap.add_argument('--remove')
    ap.add_argument('--list', action='store_true')
    a = ap.parse_args()
    clips = read()
    if a.list:
        for k, v in clips.items(): print(k, v)
        return
    if a.remove:
        shutil.rmtree(os.path.join(OUT, a.remove), ignore_errors=True)
        clips.pop(a.remove, None); write(clips); print('removed', a.remove); return
    if not a.video or not a.name:
        ap.error('give a video and --for <from>-<to>')
    probe = json.loads(subprocess.check_output(['ffprobe', '-v', 'error', '-select_streams', 'v:0', '-count_frames',
                                                '-show_entries', 'stream=nb_read_frames,width,height', '-of', 'json', a.video]))['streams'][0]
    total, w, h = int(probe['nb_read_frames']), int(probe['width']), int(probe['height'])
    n = max(2, min(a.frames, total))
    ow = min(a.width, w); oh = int(round(ow * h / w / 2)) * 2
    dest = os.path.join(OUT, a.name)
    shutil.rmtree(dest, ignore_errors=True); os.makedirs(dest)
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.check_call(['ffmpeg', '-v', 'error', '-i', a.video, '-vf', f'scale={ow}:{oh}:flags=lanczos', os.path.join(tmp, 'f-%05d.png')])
        files = sorted(os.listdir(tmp))
        size = 0
        for i in range(n):
            src = files[round(i * (len(files) - 1) / (n - 1))]
            im = Image.open(os.path.join(tmp, src)).convert('RGB')
            base = os.path.join(dest, f'f-{i:03d}')
            im.save(base + '.avif', 'AVIF', quality=58, speed=5)
            im.save(base + '.webp', 'WEBP', quality=76, method=5)
            size += os.path.getsize(base + '.avif')
    clips[a.name] = dict(frames=n, base=f'assets/transitions/{a.name}/f-', w=ow, h=oh)
    write(clips)
    print(f'{a.name}: {n} frames of {total}, {ow}x{oh}, {size / 1048576:.1f} MB as AVIF')


if __name__ == '__main__':
    main()
